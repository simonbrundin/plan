//! Databaslager.
//!
//! SQL:en är densamma som i Go-tjänsten (`src/api/internal/database`):
//! samma DDL, samma seed. Det gör att båda tjänsterna kan köra mot samma
//! databas under migreringen.

use sqlx::postgres::{PgPool, PgPoolOptions};

use crate::config::Config;

/// Startar migreringarna och returnerar en ansluten pool.
///
/// Samma ordning som i Go: api_keys-scope först, sedan agentkörningarnas
/// tillstånd, sedan agent_run_events och agent_approvals.
pub async fn connect(config: &Config) -> Result<PgPool, sqlx::Error> {
    let url = config
        .database_url
        .as_deref()
        .ok_or_else(|| sqlx::Error::Configuration("DATABASE_URL saknas".into()))?;

    let pool = PgPoolOptions::new()
        .max_connections(10)
        .acquire_timeout(std::time::Duration::from_secs(10))
        .connect(url)
        .await?;

    migrate(&pool).await?;

    Ok(pool)
}

/// Kör samma DDL som Go-tjänsten kör vid start.
async fn migrate(pool: &PgPool) -> Result<(), sqlx::Error> {
    sqlx::raw_sql(
        r#"
        ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS scope VARCHAR(16) NOT NULL DEFAULT 'full';
        "#,
    )
    .execute(pool)
    .await?;

    // Agentkörningarnas tillstånd har bytt namn: "blocked" heter nu
    // "waiting_approval" och "done" heter nu "succeeded".
    //
    // Constrainten måste bort först - annars går det inte att skriva de nya
    // värdena. Sedan byts raderna, och constrainten sätts tillbaka med de nya
    // värdena. Alltihop sker i en implicit transaktion.
    sqlx::raw_sql(
        r#"
        ALTER TABLE agent_runs DROP CONSTRAINT IF EXISTS agent_runs_valid_status;
        UPDATE agent_runs SET status = 'waiting_approval' WHERE status = 'blocked';
        UPDATE agent_runs SET status = 'succeeded' WHERE status = 'done';
        ALTER TABLE agent_runs ADD CONSTRAINT agent_runs_valid_status
            CHECK ("status" IN ('queued', 'running', 'waiting_approval', 'succeeded', 'failed', 'cancelled'));
        "#,
    )
    .execute(pool)
    .await?;

    sqlx::raw_sql(
        r#"
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS trigger VARCHAR(16) NOT NULL DEFAULT 'user';
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS initiator TEXT NOT NULL DEFAULT '';
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS agent_profile VARCHAR(16) NOT NULL DEFAULT 'coding';
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS result TEXT NOT NULL DEFAULT '';
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
        ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS finished_at TIMESTAMPTZ;
        CREATE TABLE IF NOT EXISTS agent_run_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
            type VARCHAR(64) NOT NULL,
            phase VARCHAR(16) NOT NULL DEFAULT '',
            payload JSONB NOT NULL DEFAULT '{}'::jsonb,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS agent_run_events_run_idx
            ON agent_run_events (agent_run_id, created_at, id);
        "#,
    )
    .execute(pool)
    .await?;

    sqlx::raw_sql(
        r#"
        CREATE TABLE IF NOT EXISTS agent_approvals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
            goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
            title VARCHAR(255) NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            status VARCHAR(16) NOT NULL DEFAULT 'pending',
            decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
            feedback TEXT NOT NULL DEFAULT '',
            consequence TEXT NOT NULL DEFAULT '',
            verification_plan TEXT NOT NULL DEFAULT '',
            payload JSONB NOT NULL DEFAULT '{}'::jsonb,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            decided_at TIMESTAMPTZ
        );
        CREATE INDEX IF NOT EXISTS agent_approvals_run_idx
            ON agent_approvals (agent_run_id, created_at, id);
        CREATE INDEX IF NOT EXISTS agent_approvals_pending_idx
            ON agent_approvals (status) WHERE status = 'pending';
        "#,
    )
    .execute(pool)
    .await?;

    Ok(())
}

/// Säkerställer att raderna applikationen behöver finns.
///
/// Schemat appliceras av Atlas-operatorn i deklarativt läge, som bara hanterar
/// DDL - INSERT-raderna i schemafilen körs aldrig. Applikationen seedar därför
/// själv, vilket också gör att en ny databas går att använda direkt.
pub async fn ensure_seed_data(pool: &PgPool) -> Result<(), sqlx::Error> {
    // Statusar som målen går igenom. Ordningen spelar roll: goals-tabellen
    // har status_id 1 (define) som standard.
    sqlx::raw_sql(
        r#"
        INSERT INTO statuses (name, label) VALUES
            ('define', 'Defining'),
            ('plan', 'Planning'),
            ('execute', 'Executing'),
            ('verify', 'Verifying'),
            ('completed', 'Completed')
        ON CONFLICT (name) DO NOTHING
        "#,
    )
    .execute(pool)
    .await?;

    // Root-målet är förälder till alla toppnivåmål.
    sqlx::raw_sql(
        r#"
        INSERT INTO goals (id, title, icon) VALUES (1, 'Root', 'heroicons:home')
        ON CONFLICT (id) DO NOTHING
        "#,
    )
    .execute(pool)
    .await?;

    // Root-målet sätts in med explicit id, vilket lämnar identitetssekvensen
    // efter - annars kolliderar det första målet i appen med Root.
    sqlx::raw_sql(
        r#"
        SELECT setval(
            pg_get_serial_sequence('goals', 'id'),
            GREATEST((SELECT COALESCE(MAX(id), 0) + 1 FROM goals), 1)
        )
        "#,
    )
    .execute(pool)
    .await?;

    Ok(())
}
