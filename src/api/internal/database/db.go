package database

import (
	"context"
	"fmt"
	"os"

	"github.com/jackc/pgx/v5/pgxpool"
)

var pool *pgxpool.Pool

// Connect establishes a connection to the PostgreSQL database
func Connect(ctx context.Context) error {
	databaseURL := os.Getenv("DATABASE_URL")
	if databaseURL == "" {
		return fmt.Errorf("DATABASE_URL environment variable is required")
	}

	var err error
	pool, err = pgxpool.New(ctx, databaseURL)
	if err != nil {
		return fmt.Errorf("unable to create connection pool: %w", err)
	}

	// Test the connection
	if err := pool.Ping(ctx); err != nil {
		return fmt.Errorf("unable to ping database: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS scope VARCHAR(16) NOT NULL DEFAULT 'full';
	`); err != nil {
		return fmt.Errorf("unable to ensure api key scope column: %w", err)
	}

	// Agentkörningarnas tillstånd har bytt namn: "blocked" heter nu
	// "waiting_approval" och "done" heter nu "succeeded".
	//
	// Constrainten måste bort först - annars går det inte att skriva de nya
	// värdena. Sedan byts raderna, och constrainten sätts tillbaka med de nya
	// värdena. Alltihop sker i en implicit transaktion (Postgres kör en
	// fråga med flera satser i en enda transaktion).
	//
	// Körningen är idempotent: gamla värden finns inte kvar efter första
	// körningen, och constrainten sätts tillbaka även om den redan har rätt
	// värden.
	if _, err := pool.Exec(ctx, `
		ALTER TABLE agent_runs DROP CONSTRAINT IF EXISTS agent_runs_valid_status;
		UPDATE agent_runs SET status = 'waiting_approval' WHERE status = 'blocked';
		UPDATE agent_runs SET status = 'succeeded' WHERE status = 'done';
		ALTER TABLE agent_runs ADD CONSTRAINT agent_runs_valid_status
			CHECK ("status" IN ('queued', 'running', 'waiting_approval', 'succeeded', 'failed', 'cancelled'));
	`); err != nil {
		return fmt.Errorf("unable to migrate agent run statuses: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS trigger VARCHAR(16) NOT NULL DEFAULT 'user';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS initiator TEXT NOT NULL DEFAULT '';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS agent_profile VARCHAR(16) NOT NULL DEFAULT 'coding';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS result TEXT NOT NULL DEFAULT '';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS finished_at TIMESTAMPTZ;
		CREATE TABLE IF NOT EXISTS agent_run_events (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
			type VARCHAR(64) NOT NULL,
			phase VARCHAR(16) NOT NULL DEFAULT '',
			payload JSONB NOT NULL DEFAULT '{}'::jsonb,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		);
		CREATE INDEX IF NOT EXISTS agent_run_events_run_idx
			ON agent_run_events (agent_run_id, created_at, id);
	`); err != nil {
		return fmt.Errorf("unable to ensure agent run events table: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		CREATE TABLE IF NOT EXISTS agent_approvals (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			title VARCHAR(255) NOT NULL,
			description TEXT NOT NULL DEFAULT '',
			status VARCHAR(16) NOT NULL DEFAULT 'pending',
			decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
			feedback TEXT NOT NULL DEFAULT '',
			consequence TEXT NOT NULL DEFAULT '',
			verification_plan TEXT NOT NULL DEFAULT '',
			payload JSONB NOT NULL DEFAULT '{}'::jsonb,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			decided_at TIMESTAMPTZ
		);
		CREATE INDEX IF NOT EXISTS agent_approvals_run_idx
			ON agent_approvals (agent_run_id, created_at, id);
		CREATE INDEX IF NOT EXISTS agent_approvals_pending_idx
			ON agent_approvals (status) WHERE status = 'pending';
	`); err != nil {
		return fmt.Errorf("unable to ensure agent approvals table: %w", err)
	}

	// Fasmaskinen, verifieringsplanerna och bevisen.
	//
	// Verifieringsplanen är VALFRI - ett mål utan plan fungerar precis som
	// ett mål med en plan. Planen blir villkoret för att agenten får
	// föreslå att målet är klart, och beviset visas när människan bestämmer.
	if _, err := pool.Exec(ctx, `
		ALTER TABLE goals ADD COLUMN IF NOT EXISTS completion_kind VARCHAR(16);
		ALTER TABLE goals ADD COLUMN IF NOT EXISTS approval_mode VARCHAR(16) NOT NULL DEFAULT 'plan';
		CREATE TABLE IF NOT EXISTS goal_verifications (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			type VARCHAR(16) NOT NULL DEFAULT 'bevis',
			criterion TEXT NOT NULL DEFAULT '',
			strength VARCHAR(16) NOT NULL DEFAULT 'svag',
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			CONSTRAINT goal_verifications_valid_type CHECK (type IN ('checklista', 'delmal', 'kalender', 'bevis', 'matvarde', 'kod')),
			CONSTRAINT goal_verifications_valid_strength CHECK (strength IN ('stark', 'svag')),
			CONSTRAINT goal_verifications_unique_goal UNIQUE (goal_id)
		);
		CREATE TABLE IF NOT EXISTS goal_evidence (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			verification_id INTEGER REFERENCES goal_verifications(id) ON DELETE SET NULL,
			type VARCHAR(16) NOT NULL DEFAULT 'text',
			value TEXT NOT NULL DEFAULT '',
			source VARCHAR(64) NOT NULL DEFAULT 'user',
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		);
		CREATE INDEX IF NOT EXISTS goal_evidence_goal_idx
			ON goal_evidence (goal_id, created_at);
		CREATE TABLE IF NOT EXISTS goal_verification_results (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			verification_id INTEGER REFERENCES goal_verifications(id) ON DELETE SET NULL,
			outcome VARCHAR(16) NOT NULL DEFAULT 'pending',
			note TEXT NOT NULL DEFAULT '',
			decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
			decided_at TIMESTAMPTZ,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			CONSTRAINT goal_verification_results_valid_outcome CHECK (outcome IN ('passed', 'failed', 'pending'))
		);
		CREATE INDEX IF NOT EXISTS goal_verification_results_goal_idx
			ON goal_verification_results (goal_id, created_at);
		CREATE TABLE IF NOT EXISTS goal_phase_events (
			id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			from_phase VARCHAR(16) NOT NULL DEFAULT '',
			to_phase VARCHAR(16) NOT NULL DEFAULT '',
			actor VARCHAR(16) NOT NULL DEFAULT 'human',
			forced BOOLEAN NOT NULL DEFAULT FALSE,
			reason TEXT NOT NULL DEFAULT '',
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		);
		CREATE INDEX IF NOT EXISTS goal_phase_events_goal_idx
			ON goal_phase_events (goal_id, created_at);
	`); err != nil {
		return fmt.Errorf("unable to ensure goal phase and verification tables: %w", err)
	}

	return nil
}

// GetPool returns the database connection pool
func GetPool() *pgxpool.Pool {
	return pool
}

// Close closes the database connection pool
func Close() {
	if pool != nil {
		pool.Close()
	}
}
