package database

import (
	"context"
	"fmt"
	"os"

	"github.com/jackc/pgx/v5/pgxpool"
)

var pool *pgxpool.Pool

// Connect establishes a connection to the PostgreSQL database
func Connect(ctx context.Context) error {
	databaseURL := os.Getenv("DATABASE_URL")
	if databaseURL == "" {
		return fmt.Errorf("DATABASE_URL environment variable is required")
	}

	var err error
	pool, err = pgxpool.New(ctx, databaseURL)
	if err != nil {
		return fmt.Errorf("unable to create connection pool: %w", err)
	}

	// Test the connection
	if err := pool.Ping(ctx); err != nil {
		return fmt.Errorf("unable to ping database: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		ALTER TABLE api_keys ADD COLUMN IF NOT EXISTS scope VARCHAR(16) NOT NULL DEFAULT 'full';
	`); err != nil {
		return fmt.Errorf("unable to ensure api key scope column: %w", err)
	}

	// Agentkörningarnas tillstånd har bytt namn: "blocked" heter nu
	// "waiting_approval" och "done" heter nu "succeeded". Körningen är
	// idempotent - gamla värden finns inte kvar efter första körningen.
	if _, err := pool.Exec(ctx, `
		UPDATE agent_runs SET status = 'waiting_approval' WHERE status = 'blocked';
		UPDATE agent_runs SET status = 'succeeded' WHERE status = 'done';
	`); err != nil {
		return fmt.Errorf("unable to migrate agent run statuses: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS trigger VARCHAR(16) NOT NULL DEFAULT 'user';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS initiator TEXT NOT NULL DEFAULT '';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS agent_profile VARCHAR(16) NOT NULL DEFAULT 'coding';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS result TEXT NOT NULL DEFAULT '';
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
		ALTER TABLE agent_runs ADD COLUMN IF NOT EXISTS finished_at TIMESTAMPTZ;
		CREATE TABLE IF NOT EXISTS agent_run_events (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
			type VARCHAR(64) NOT NULL,
			phase VARCHAR(16) NOT NULL DEFAULT '',
			payload JSONB NOT NULL DEFAULT '{}'::jsonb,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
		);
		CREATE INDEX IF NOT EXISTS agent_run_events_run_idx
			ON agent_run_events (agent_run_id, created_at, id);
	`); err != nil {
		return fmt.Errorf("unable to ensure agent run events table: %w", err)
	}

	if _, err := pool.Exec(ctx, `
		CREATE TABLE IF NOT EXISTS agent_approvals (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			agent_run_id INTEGER NOT NULL REFERENCES agent_runs(id) ON DELETE CASCADE,
			goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
			title VARCHAR(255) NOT NULL,
			description TEXT NOT NULL DEFAULT '',
			status VARCHAR(16) NOT NULL DEFAULT 'pending',
			decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
			feedback TEXT NOT NULL DEFAULT '',
			consequence TEXT NOT NULL DEFAULT '',
			verification_plan TEXT NOT NULL DEFAULT '',
			payload JSONB NOT NULL DEFAULT '{}'::jsonb,
			created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
			decided_at TIMESTAMPTZ
		);
		CREATE INDEX IF NOT EXISTS agent_approvals_run_idx
			ON agent_approvals (agent_run_id, created_at, id);
		CREATE INDEX IF NOT EXISTS agent_approvals_pending_idx
			ON agent_approvals (status) WHERE status = 'pending';
	`); err != nil {
		return fmt.Errorf("unable to ensure agent approvals table: %w", err)
	}

	return nil
}

// GetPool returns the database connection pool
func GetPool() *pgxpool.Pool {
	return pool
}

// Close closes the database connection pool
func Close() {
	if pool != nil {
		pool.Close()
	}
}
